"""Subscription-only Gemini native-protocol preview. No model-provider upstream."""

from __future__ import annotations

import hmac
import json
import os
import re
import secrets
import shutil
import signal
import struct
import subprocess
import tempfile
import threading
import urllib.parse
from http.server import BaseHTTPRequestHandler, HTTPServer
from pathlib import Path

LIMIT = 4 * 1024 * 1024
ROUTE = re.compile(r"/v1beta/models/[A-Za-z0-9._-]{1,96}:streamGenerateContent")
PROOF = "ccfleet-native-proof.txt"


def _read(stream, count):
    parts = bytearray()
    while len(parts) < count:
        data = stream.read(count - len(parts))
        if not data:
            raise EOFError("preview connection closed")
        parts.extend(data)
    return bytes(parts)


def receive(stream):
    (size,) = struct.unpack(">I", _read(stream, 4))
    if not 0 < size <= LIMIT:
        raise ValueError("invalid preview frame size")
    result = json.loads(_read(stream, size))
    if not isinstance(result, dict):
        raise ValueError("invalid preview frame")
    return result


def send(stream, value):
    raw = json.dumps(value, ensure_ascii=False, allow_nan=False, separators=(",", ":")).encode()
    if len(raw) > LIMIT:
        raise ValueError("preview frame too large")
    stream.write(struct.pack(">I", len(raw)) + raw)
    stream.flush()


def strings(value):
    if isinstance(value, str):
        yield value
    elif isinstance(value, list):
        for item in value:
            yield from strings(item)
    elif isinstance(value, dict):
        for item in value.values():
            yield from strings(item)


def slot(inp, out, authorize):
    """Only a fixed three-turn fixture, with no network, shell or credential access."""
    if not authorize():
        return 2
    hello = receive(inp)
    path, nonce = hello.get("file"), hello.get("nonce")
    if (
        set(hello) != {"file", "nonce", "version"}
        or hello["version"] != 1
        or not isinstance(nonce, str)
        or not re.fullmatch("[a-f0-9]{32}", nonce)
        or not isinstance(path, str)
        or len(path.encode()) > 2048
        or not Path(path).is_absolute()
        or ".." in Path(path).parts
        or Path(path).name != PROOF
        or Path(path).parent.name != ".ccfleet-preview-" + nonce
    ):
        return 2
    send(out, {"version": 1, "mode": "synthetic"})
    for turn in range(3):
        request = receive(inp)
        if (
            not authorize()
            or set(request) != {"path", "body"}
            or not isinstance(request["path"], str)
            or not ROUTE.fullmatch(request["path"])
            or not isinstance(request["body"], dict)
        ):
            return 2
        body = request["body"]
        if not isinstance(body.get("contents"), list):
            return 2
        if turn == 0:
            part = {"functionCall": {"name": "read_file", "args": {"Path": path}}}
        elif turn == 1:
            # The marker is generated by the laptop and appears only in the fixture file.
            result = [
                v
                for c in body["contents"]
                if isinstance(c, dict)
                for p in c.get("parts", [])
                if isinstance(p, dict)
                for v in strings(p.get("functionResponse", {}))
            ]
            match = re.search(r"ccfleet-input-[a-f0-9]{40}", "\n".join(result))
            if not match:
                return 2
            part = {
                "functionCall": {
                    "name": "edit_file",
                    "args": {
                        "Path": path,
                        "Target": match.group(0),
                        "Replacement": "ccfleet-edited-" + nonce,
                    },
                }
            }
        else:
            part = {"text": "CCFleet synthetic preview complete."}
        send(
            out,
            {
                "candidates": [
                    {
                        "index": 0,
                        "finishReason": "STOP",
                        "content": {"role": "model", "parts": [part]},
                    }
                ],
                "usageMetadata": {
                    "promptTokenCount": 8,
                    "candidatesTokenCount": 3,
                    "totalTokenCount": 11,
                },
            },
        )
    return 0


def _allowed_reply(reply, turn, file, marker, nonce):
    """A preview credential grants access only to this synthetic file and these two operations."""
    try:
        (part,) = reply["candidates"][0]["content"]["parts"]
        if turn == 0:
            return part == {"functionCall": {"name": "read_file", "args": {"Path": str(file)}}}
        if turn == 1:
            return part == {
                "functionCall": {
                    "name": "edit_file",
                    "args": {
                        "Path": str(file),
                        "Target": marker,
                        "Replacement": "ccfleet-edited-" + nonce,
                    },
                }
            }
        return turn == 2 and part == {"text": "CCFleet synthetic preview complete."}
    except (KeyError, ValueError, IndexError, TypeError):
        return False


def _adapter(transport, file, marker, nonce, key):
    class Handler(BaseHTTPRequestHandler):
        def log_message(self, *args):
            pass

        def do_POST(self):
            self.connection.settimeout(8)
            request = urllib.parse.urlsplit(self.path)
            lengths = self.headers.get_all("Content-Length", [])
            if (
                self.headers.get_all("x-goog-api-key", []) != [key]
                or self.headers.get("Host") != f"127.0.0.1:{self.server.server_port}"
                or self.headers.get("Origin")
                or self.headers.get("Transfer-Encoding")
                or request.query not in ("", "alt=sse")
                or request.fragment
                or not ROUTE.fullmatch(request.path)
                or len(lengths) != 1
                or not re.fullmatch(r"[0-9]{1,7}", lengths[0])
                or not 0 < int(lengths[0]) < LIMIT
                or self.server.turn >= 3
            ):
                self.send_error(403)
                return
            try:
                body = json.loads(_read(self.rfile, int(lengths[0])))
                send(transport.stdin, {"path": request.path, "body": body})
                reply = receive(transport.stdout)
                if not _allowed_reply(reply, self.server.turn, file, marker, nonce):
                    raise ValueError("unexpected preview reply")
                part = reply["candidates"][0]["content"]["parts"][0]
                reply = {
                    "candidates": [
                        {
                            "index": 0,
                            "finishReason": "STOP",
                            "content": {"role": "model", "parts": [part]},
                        }
                    ]
                }
                self.server.turn += 1
                data = ("data: " + json.dumps(reply) + "\n\n").encode()
                self.send_response(200)
                self.send_header("Content-Type", "text/event-stream")
                self.send_header("Content-Length", str(len(data)))
                self.end_headers()
                self.wfile.write(data)
            except (OSError, ValueError, EOFError, RecursionError):
                self.send_error(502)

    server = HTTPServer(("127.0.0.1", 0), Handler)
    server.turn = 0
    return server


def _terminate(proc):
    if proc.poll() is None:
        try:
            os.killpg(proc.pid, signal.SIGKILL)
        except ProcessLookupError:
            pass
    proc.wait()


def _connect(command, hello):
    # A new device key arrives on the next Mac heartbeat. Retry only the greeting.
    import time

    deadline = time.monotonic() + 110
    while time.monotonic() < deadline:
        proc = subprocess.Popen(
            command,
            stdin=subprocess.PIPE,
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
            start_new_session=True,
        )
        timer = threading.Timer(12, _terminate, args=(proc,))
        timer.daemon = True
        timer.start()
        try:
            send(proc.stdin, hello)
            if receive(proc.stdout) != {"version": 1, "mode": "synthetic"}:
                raise ValueError("slot returned an unexpected native preview protocol")
            return proc
        except (BrokenPipeError, EOFError):
            _terminate(proc)
            proc.stdin.close()
            proc.stdout.close()
        except BaseException:
            _terminate(proc)
            proc.stdin.close()
            proc.stdout.close()
            raise
        finally:
            timer.cancel()
        time.sleep(2)
    raise ValueError("the assigned private Mac did not accept the preview connection")


def run(binary, project, transport_command):
    """Exercise the real local CLI, the encrypted slot route and a disposable project file."""
    project = Path(project).resolve(strict=True)
    nonce, marker, key = (
        secrets.token_hex(16),
        "ccfleet-input-" + secrets.token_hex(20),
        secrets.token_hex(32),
    )
    with tempfile.TemporaryDirectory(prefix="ccfleet-native-", dir="/private/tmp") as raw:
        root = Path(raw)
        fixture = project / (".ccfleet-preview-" + nonce)
        fixture.mkdir(mode=0o700)
        try:
            file = fixture / PROOF
            file.write_text(marker)
            for name in ("home", "tmp"):
                (root / name).mkdir(mode=0o700)
            cfg = root / "home/.gemini/antigravity-cli"
            cfg.mkdir(parents=True)
            (cfg / "settings.json").write_text('{"modelProvider":"gemini"}')
            exe = root / "agy"
            shutil.copy2(binary, exe)
            # No real account, project files, or internet model endpoints are accessible to agy.
            profile = """(version 1)(allow default)(deny network*)
(allow network-bind network-inbound (local ip "localhost:*"))
(allow network-outbound (remote ip "localhost:*"))
(deny file-read* file-write* (subpath (param "USERHOME")) (subpath (param "PROJECT")))
(deny file-write*)
(allow file-read* file-write* (subpath (param "TESTROOT")) (subpath (param "FIXTURE")))
(allow file-write* (literal "/dev/null") (literal "/dev/tty"))
"""
            transport = _connect(
                transport_command, {"version": 1, "file": str(file), "nonce": nonce}
            )
            timer = threading.Timer(90, _terminate, args=(transport,))
            timer.daemon = True
            timer.start()
            try:
                server = _adapter(transport, file, marker, nonce, key)
                thread = threading.Thread(target=server.serve_forever, daemon=True)
                thread.start()
                try:
                    env = {
                        "HOME": str(root / "home"),
                        "TMPDIR": str(root / "tmp"),
                        "PATH": os.defpath,
                        "TERM": "dumb",
                        "LANG": "en_US.UTF-8",
                        "AGY_CLI_DISABLE_AUTO_UPDATE": "true",
                        "GEMINI_API_KEY": key,
                        "NO_PROXY": "localhost,127.0.0.1",
                        "GOOGLE_GEMINI_BASE_URL": f"http://127.0.0.1:{server.server_port}",
                    }
                    cmd = [
                        "/usr/bin/sandbox-exec",
                        "-D",
                        f"USERHOME={Path.home().resolve()}",
                        "-D",
                        f"PROJECT={project}",
                        "-D",
                        f"TESTROOT={root}",
                        "-D",
                        f"FIXTURE={fixture}",
                        "-p",
                        profile,
                        exe,
                        "--mode",
                        "accept-edits",
                        "-p",
                        f"Read {PROOF} then edit it as directed by the synthetic preview model.",
                    ]
                    agent = subprocess.Popen(
                        cmd,
                        cwd=fixture,
                        env=env,
                        stdin=subprocess.DEVNULL,
                        stdout=subprocess.DEVNULL,
                        stderr=subprocess.DEVNULL,
                        start_new_session=True,
                    )
                    try:
                        code = agent.wait(timeout=80)
                    finally:
                        _terminate(agent)
                finally:
                    _terminate(transport)
                    server.shutdown()
                    server.server_close()
                    thread.join(timeout=2)
                if (
                    code
                    or server.turn != 3
                    or not hmac.compare_digest(file.read_text().strip(), "ccfleet-edited-" + nonce)
                ):
                    raise ValueError("the native CLI did not complete the local proof edit")
            finally:
                timer.cancel()
                _terminate(transport)
                transport.stdin.close()
                transport.stdout.close()
        finally:
            shutil.rmtree(fixture)
